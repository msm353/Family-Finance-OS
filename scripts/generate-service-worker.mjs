import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(projectRoot, "dist");

async function listFiles(directory, prefix = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name === ".vite" || entry.name === "sw.js") continue;
    const relative = path.posix.join(prefix, entry.name);
    if (entry.isDirectory()) {
      files.push(...await listFiles(path.join(directory, entry.name), relative));
    } else if (entry.isFile()) {
      files.push(relative);
    }
  }
  return files;
}

const files = (await listFiles(dist)).sort();
if (!files.includes("index.html") || !files.includes("manifest.webmanifest")) {
  throw new Error("The production app shell is incomplete.");
}

const hash = createHash("sha256");
for (const file of files) {
  hash.update(file);
  hash.update(await readFile(path.join(dist, file)));
}
const version = hash.digest("hex").slice(0, 12);
const resources = ["./", ...files.map((file) => `./${file}`)];

const serviceWorker = `/* Generated by scripts/generate-service-worker.mjs. */
const CACHE_NAME = "ffos-shell-${version}";
const APP_RESOURCES = ${JSON.stringify(resources, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_RESOURCES)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith("ffos-shell-") && name !== CACHE_NAME)
      .map((name) => caches.delete(name)));
    await self.clients.claim();
  })());
});

self.addEventListener("message", (event) => {
  if (event.data?.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  const url = new URL(request.url);
  const scope = new URL(self.registration.scope);
  if (request.method !== "GET" || url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return;

  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    if (request.mode === "navigate") {
      return await cache.match(new URL("./index.html", scope).href) ?? fetch(request);
    }
    return await cache.match(request, { ignoreSearch: true, ignoreVary: true }) ?? fetch(request);
  })());
});
`;

await writeFile(path.join(dist, "sw.js"), serviceWorker);
process.stdout.write(`Generated offline shell ${version} with ${resources.length} resources.\n`);
